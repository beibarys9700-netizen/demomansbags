export type Lang = 'kz' | 'ru' | 'en';
export type Cur = 'KZT' | 'USD';

export const CURRENCY_RATES: Record<Cur, { symbol: string; rate: number; label: string }> = {
  KZT: { symbol: '₸', rate: 1, label: 'KZT' },
  USD: { symbol: '$', rate: 1 / 480, label: 'USD' },
};

export const formatPrice = (kztAmount: number, cur: Cur): string => {
  const { symbol, rate } = CURRENCY_RATES[cur];
  const value = kztAmount * rate;
  if (cur === 'KZT') {
    return `${symbol} ${kztAmount.toLocaleString('ru-RU')}`;
  }
  return `${symbol} ${value.toLocaleString('en-US', { minimumFractionDigits: 0, maximumFractionDigits: 0 })}`;
};

